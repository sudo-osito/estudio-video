s.oir("Lo armé porque editar", true); s.oir("lo", true); s.oir("armé porque editar me quitaba", true); ok(s.tomas === 1 && s.cursor === 6, "retoma partida en tramos: tomas=" + s.tomas + " cursor=" + s.cursor);
s = crearSeguidor(g.slice(0, 2));
